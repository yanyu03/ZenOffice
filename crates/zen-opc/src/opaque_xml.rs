//! Read-only descriptor check for one explicitly declared, owned opaque XML part.
//! This is NOT package/edit admission and is not called by any write path.
//! Caller ownership/semantic independence is a trust premise, not inferred evidence.

use crate::opc::{RELS_NS, TYPES_NS};
use crate::{
    ContentTypes, OpcError, Relationships, Result, ZipArchive, normalize_part_name, resolve_target,
};
use sha2::{Digest, Sha256};
use std::collections::BTreeSet;

pub const CUSTOM_XML_REL: &str =
    "http://schemas.openxmlformats.org/officeDocument/2006/relationships/customXml";
const MAX_INPUT: usize = 16 * 1024 * 1024;
const MAX_XML: usize = 1024 * 1024;
const MAX_PARTS: usize = 256;
const MAX_TOTAL: usize = 32 * 1024 * 1024;

/// Explicit input, never generated by auto-discovery.
#[derive(Clone, Debug)]
pub struct OpaqueXmlDeclaration {
    pub source_sha256: [u8; 32],
    pub part_name: String,
    pub payload_sha256: [u8; 32],
    pub payload_bytes: usize,
    pub content_type: String,
    pub relationship_id: String,
    /// Exact raw workbook relationship target, including relative spelling.
    pub relationship_target: String,
    pub controlled_owned_source: bool,
    pub semantically_independent: bool,
    pub review_basis: String,
}

/// Only a descriptor receipt; deliberately has no capability to authorize edits.
#[derive(Debug)]
pub struct OpaqueXmlReceipt {
    source_sha256: [u8; 32],
    payload_sha256: [u8; 32],
}
impl OpaqueXmlReceipt {
    pub fn source_sha256(&self) -> [u8; 32] {
        self.source_sha256
    }
    pub fn payload_sha256(&self) -> [u8; 32] {
        self.payload_sha256
    }
}
pub fn sha256(bytes: &[u8]) -> [u8; 32] {
    Sha256::digest(bytes).into()
}
fn reject(reason: &str) -> OpcError {
    OpcError::Xml(format!("opaque XML descriptor: {reason}"))
}
fn canonical(name: &str) -> Result<String> {
    if !name.is_ascii()
        || name.contains(['%', '\\', ':', '?', '#'])
        || name.ends_with('/')
        || name.contains("//")
    {
        return Err(reject("ambiguous part name"));
    }
    let normalized = normalize_part_name(name)?;
    if normalized != name {
        return Err(reject("non-canonical part name"));
    }
    Ok(normalized)
}
fn xml(bytes: &[u8]) -> Result<roxmltree::Document<'_>> {
    if bytes.len() > MAX_XML {
        return Err(reject("XML budget"));
    }
    let text = std::str::from_utf8(bytes).map_err(|_| reject("non UTF-8 XML"))?;
    // roxmltree permits empty DTDs even with allow_dtd=false; refuse those too.
    if text.contains("<!DOCTYPE") || text.contains("<!ENTITY") {
        return Err(reject("DTD/entity"));
    }
    roxmltree::Document::parse_with_options(
        text,
        roxmltree::ParsingOptions {
            allow_dtd: false,
            nodes_limit: 16_384,
        },
    )
    .map_err(|_| reject("invalid/over-budget XML"))
}

fn metadata_shape(
    doc: &roxmltree::Document<'_>,
    root_name: &str,
    namespace: &str,
    rows: &[(&str, &[&str])],
) -> Result<()> {
    let root = doc.root_element();
    if !root.has_tag_name((namespace, root_name)) || root.attributes().len() != 0 {
        return Err(reject("unknown metadata root/attributes"));
    }
    for node in root.children() {
        if node.is_comment() {
            continue;
        }
        if node.is_text() && node.text().is_some_and(|s| s.trim().is_empty()) {
            continue;
        }
        if !node.is_element() || node.tag_name().namespace() != Some(namespace) {
            return Err(reject("unknown metadata node"));
        }
        let fields = rows
            .iter()
            .find(|(name, _)| *name == node.tag_name().name())
            .map(|(_, fields)| *fields)
            .ok_or_else(|| reject("unknown metadata row"))?;
        if node
            .attributes()
            .any(|a| a.namespace().is_some() || !fields.contains(&a.name()))
            || node
                .children()
                .any(|n| !n.is_text() || n.text().is_none_or(|s| !s.trim().is_empty()))
        {
            return Err(reject("unknown metadata attributes/content"));
        }
    }
    Ok(())
}

fn owner(rels: &str) -> Result<String> {
    if rels == "/_rels/.rels" {
        return Ok("/".into());
    }
    let (dir, file) = rels
        .rsplit_once("/_rels/")
        .ok_or_else(|| reject("relationship location"))?;
    let file = file
        .strip_suffix(".rels")
        .ok_or_else(|| reject("relationship suffix"))?;
    canonical(&format!("{dir}/{file}"))
}

/// Check the initial package identity and the complete single-part declaration.
/// A receipt does not certify absence of arbitrary application-level dependencies.
/// Existing package safety, edit admission, history and save gates remain required.
pub fn validate_opaque_xml_descriptor(
    bytes: &[u8],
    declarations: &[OpaqueXmlDeclaration],
) -> Result<OpaqueXmlReceipt> {
    validate_descriptor(bytes, declarations, true)
}

fn validate_descriptor(
    bytes: &[u8],
    declarations: &[OpaqueXmlDeclaration],
    initial: bool,
) -> Result<OpaqueXmlReceipt> {
    if bytes.len() > MAX_INPUT {
        return Err(reject("input budget"));
    }
    if declarations.len() != 1 {
        return Err(reject("exactly one declaration required"));
    }
    let d = &declarations[0];
    if !d.controlled_owned_source
        || !d.semantically_independent
        || d.review_basis.trim().is_empty()
        || d.review_basis.len() > 4096
        || d.relationship_id.is_empty()
        || d.relationship_id.len() > 256
        || d.relationship_target.len() > 1024
        || d.part_name.len() > 1024
        || d.content_type.len() > 256
    {
        return Err(reject("missing/over-budget caller declaration"));
    }
    if initial && sha256(bytes) != d.source_sha256 {
        return Err(reject("source identity"));
    }
    canonical(&d.part_name)?;
    if !d.part_name.starts_with("/customXml/")
        || !d.part_name.ends_with(".xml")
        || d.content_type != "application/xml"
    {
        return Err(reject("part/media scope"));
    }
    // ZIP reader retains its own pre-inflate 64MiB/256MiB limits.
    // These stricter post-read limits do not describe peak heap allocation.
    let zip = ZipArchive::read(bytes)?;
    if zip.entries.len() > MAX_PARTS {
        return Err(reject("part count budget"));
    }
    let mut names = BTreeSet::new();
    let mut total = 0usize;
    for e in &zip.entries {
        let name = canonical(&format!("/{}", e.name))?;
        if !names.insert(name.to_ascii_lowercase()) {
            return Err(reject("duplicate/case alias"));
        }
        total = total
            .checked_add(e.data.len())
            .ok_or_else(|| reject("size overflow"))?;
        if total > MAX_TOTAL {
            return Err(reject("expanded size budget"));
        }
        let lower = name.to_ascii_lowercase();
        if lower.contains("customxml/") && name != d.part_name {
            return Err(reject("undeclared custom XML/properties"));
        }
        if lower.contains("_xmlsignatures/")
            || lower.contains("vbaproject")
            || lower.contains("activex/")
            || lower.contains("embeddings/")
        {
            return Err(reject("active/signed package"));
        }
        if lower.ends_with(".xml") || lower.ends_with(".rels") {
            let doc = xml(&e.data)?;
            if doc.descendants().any(|n| {
                n.is_element()
                    && matches!(
                        n.tag_name().name(),
                        "dataBinding"
                            | "xmlMaps"
                            | "MapInfo"
                            | "mapInfo"
                            | "xmlCellPr"
                            | "singleXmlCells"
                            | "connections"
                            | "externalLink"
                            | "datastoreItem"
                            | "schemaRef"
                            | "extLst"
                            | "documentProtection"
                            | "writeProtection"
                    )
            }) {
                return Err(reject(
                    "binding/extension/protection requires separate review",
                ));
            }
        }
    }
    let payload = zip
        .get(d.part_name.trim_start_matches('/'))
        .ok_or_else(|| reject("missing payload"))?;
    if payload.len() != d.payload_bytes || sha256(payload) != d.payload_sha256 {
        return Err(reject("payload identity"));
    }
    let leaf = xml(payload)?;
    if leaf.descendants().filter(|n| n.is_element()).count() != 1
        || leaf.descendants().any(|n| n.is_comment() || n.is_pi())
    {
        return Err(reject("only leaf text XML supported"));
    }
    let ct_bytes = zip
        .get("[Content_Types].xml")
        .ok_or_else(|| reject("missing content types"))?;
    let ct_doc = xml(ct_bytes)?;
    metadata_shape(
        &ct_doc,
        "Types",
        TYPES_NS,
        &[
            ("Default", &["Extension", "ContentType"]),
            ("Override", &["PartName", "ContentType"]),
        ],
    )?;
    let mut defaults = BTreeSet::new();
    let mut overrides = BTreeSet::new();
    for n in ct_doc.root_element().children().filter(|n| n.is_element()) {
        if n.tag_name().namespace() != Some(TYPES_NS) {
            return Err(reject("content type namespace"));
        }
        match n.tag_name().name() {
            "Default" => {
                let ext = n
                    .attribute("Extension")
                    .ok_or_else(|| reject("missing extension"))?;
                if !defaults.insert(ext.to_ascii_lowercase()) {
                    return Err(reject("duplicate media default"));
                }
            }
            "Override" => {
                let part = n
                    .attribute("PartName")
                    .ok_or_else(|| reject("missing override part"))?;
                canonical(part)?;
                if !overrides.insert(part.to_ascii_lowercase()) {
                    return Err(reject("duplicate media override"));
                }
            }
            _ => return Err(reject("unknown media entry")),
        }
    }
    let ct = ContentTypes::parse(
        std::str::from_utf8(ct_bytes).map_err(|_| reject("content types UTF-8"))?,
    )?;
    if ct.content_type_for(&d.part_name) != Some(d.content_type.as_str()) {
        return Err(reject("media identity"));
    }
    if zip.get("xl/workbook.xml").is_none() {
        return Err(reject("missing workbook owner"));
    }
    let mut incoming = 0usize;
    for e in &zip.entries {
        if !e.name.ends_with(".rels") {
            continue;
        }
        let src = owner(&format!("/{}", e.name))?;
        if src != "/" && zip.get(src.trim_start_matches('/')).is_none() {
            return Err(reject("orphan relationship owner"));
        }
        let doc = xml(&e.data)?;
        metadata_shape(
            &doc,
            "Relationships",
            RELS_NS,
            &[("Relationship", &["Id", "Type", "Target", "TargetMode"])],
        )?;
        if doc.root_element().tag_name().namespace() != Some(RELS_NS) {
            return Err(reject("relationship namespace"));
        }
        let rels =
            Relationships::parse(std::str::from_utf8(&e.data).map_err(|_| reject("rels UTF-8"))?)?;
        let mut ids = BTreeSet::new();
        for r in rels.items {
            if !ids.insert(r.id.clone()) {
                return Err(reject("duplicate relationship ID"));
            }
            // This standalone narrow checker rejects all external relationships.
            if r.mode.as_deref().is_some_and(|m| m != "Internal")
                || r.target.contains(['%', '\\', ':', '?', '#'])
            {
                return Err(reject("external/ambiguous relationship"));
            }
            if r.target.contains("//") {
                return Err(reject("ambiguous target segments"));
            }
            let mut depth = if r.target.starts_with('/') || src == "/" {
                0
            } else {
                src.trim_start_matches('/').split('/').count() - 1
            };
            for segment in r.target.split('/') {
                match segment {
                    "" | "." => {}
                    ".." => {
                        if depth == 0 {
                            return Err(reject("target traversal above root"));
                        }
                        depth -= 1;
                    }
                    _ => depth += 1,
                }
            }
            let target = resolve_target(&src, &r.target)?;
            canonical(&target)?;
            if target.eq_ignore_ascii_case(&d.part_name) {
                incoming += 1;
                if target != d.part_name
                    || src != "/xl/workbook.xml"
                    || r.ty != CUSTOM_XML_REL
                    || r.id != d.relationship_id
                    || r.target != d.relationship_target
                {
                    return Err(reject("owner/relationship identity"));
                }
            } else if r.ty == CUSTOM_XML_REL {
                return Err(reject("undeclared custom XML relationship"));
            }
            if src == d.part_name {
                return Err(reject("outgoing custom XML relationship"));
            }
        }
    }
    if incoming != 1 {
        return Err(reject("single workbook relationship required"));
    }
    Ok(OpaqueXmlReceipt {
        source_sha256: sha256(bytes),
        payload_sha256: d.payload_sha256,
    })
}

/// Immutable preservation invariants bound to the explicitly reviewed initial
/// bytes. This checker is not an editor/session capability. A caller must still
/// establish candidate lineage and run every ordinary edit/package/save gate.
#[derive(Debug)]
pub struct OpaqueXmlPolicy {
    declaration: OpaqueXmlDeclaration,
    relationship_xml: Vec<u8>,
    media_xml: Vec<u8>,
    identity: [u8; 32],
}
const MAX_POLICY_BYTES: usize = 16 * 1024;

impl OpaqueXmlPolicy {
    pub(crate) fn declared_part(&self) -> &str { &self.declaration.part_name }

    /// Does not discover, infer or update a declaration.
    pub fn bind_initial(bytes: &[u8], declaration: &OpaqueXmlDeclaration) -> Result<Self> {
        validate_opaque_xml_descriptor(bytes, std::slice::from_ref(declaration))?;
        let (relationship_xml, media_xml) = metadata_rows(bytes, declaration)?;
        let strings = declaration.part_name.len()
            + declaration.content_type.len()
            + declaration.relationship_id.len()
            + declaration.relationship_target.len()
            + declaration.review_basis.len();
        if strings + relationship_xml.len() + media_xml.len() > MAX_POLICY_BYTES {
            return Err(reject("policy retained descriptor budget"));
        }
        let mut hash = Sha256::new();
        hash.update(b"ZenOffice opaque XML policy v1\0");
        // Length-prefixed fields avoid concatenation ambiguity. Fixed-width
        // lengths and sizes make identity independent of host pointer width.
        for value in [
            declaration.source_sha256.as_slice(),
            declaration.part_name.as_bytes(),
            declaration.payload_sha256.as_slice(),
            &(declaration.payload_bytes as u64).to_le_bytes(),
            declaration.content_type.as_bytes(),
            declaration.relationship_id.as_bytes(),
            declaration.relationship_target.as_bytes(),
            &[
                declaration.controlled_owned_source as u8,
                declaration.semantically_independent as u8,
            ],
            declaration.review_basis.as_bytes(),
            relationship_xml.as_slice(),
            media_xml.as_slice(),
        ] {
            hash.update((value.len() as u64).to_le_bytes());
            hash.update(value);
        }
        Ok(Self {
            declaration: declaration.clone(),
            relationship_xml,
            media_xml,
            identity: hash.finalize().into(),
        })
    }

    pub fn identity(&self) -> [u8; 32] {
        self.identity
    }
    pub fn initial_source_sha256(&self) -> [u8; 32] {
        self.declaration.source_sha256
    }
    /// Descriptor string/row payload bytes only, not exact heap allocation.
    pub fn retained_descriptor_bytes(&self) -> usize {
        self.declaration.part_name.len()
            + self.declaration.content_type.len()
            + self.declaration.relationship_id.len()
            + self.declaration.relationship_target.len()
            + self.declaration.review_basis.len()
            + self.relationship_xml.len()
            + self.media_xml.len()
    }

    /// Reopening as the initial source must match the original archive SHA.
    /// A candidate frame must never silently be adopted as a new initial source.
    pub fn validate_initial(&self, bytes: &[u8]) -> Result<OpaqueXmlReceipt> {
        validate_opaque_xml_descriptor(bytes, std::slice::from_ref(&self.declaration))?;
        self.validate_candidate(bytes)
    }

    /// Recheck preserved invariants without requiring normal changed archive
    /// bytes to equal the initial archive hash. Never updates the policy or its
    /// source hash. A success is NOT proof that this frame arose from an allowed
    /// edit or belongs to a session: that obligation stays with the transaction.
    /// The receipt's source_sha256 identifies THESE checked bytes.
    pub fn validate_candidate(&self, bytes: &[u8]) -> Result<OpaqueXmlReceipt> {
        let receipt = validate_descriptor(bytes, std::slice::from_ref(&self.declaration), false)?;
        let (relationship_xml, media_xml) = metadata_rows(bytes, &self.declaration)?;
        if relationship_xml != self.relationship_xml || media_xml != self.media_xml {
            return Err(reject("preserved relationship/media row changed"));
        }
        Ok(receipt)
    }
}

/// Retain only the exact owning relationship and effective media declaration,
/// not a whole workbook relationship file (other valid edits may invalidate a
/// calcChain). Default -> override migration is intentionally refused.
fn metadata_rows(bytes: &[u8], d: &OpaqueXmlDeclaration) -> Result<(Vec<u8>, Vec<u8>)> {
    let zip = ZipArchive::read(bytes)?;
    let relationships = zip
        .get("xl/_rels/workbook.xml.rels")
        .ok_or_else(|| reject("missing workbook relationship file"))?;
    let rel_doc = xml(relationships)?;
    let rel = rel_doc
        .root_element()
        .children()
        .find(|n| n.is_element() && n.attribute("Id") == Some(d.relationship_id.as_str()))
        .ok_or_else(|| reject("missing owning relationship"))?;
    let content_types = zip
        .get("[Content_Types].xml")
        .ok_or_else(|| reject("missing content types"))?;
    let media_doc = xml(content_types)?;
    let root = media_doc.root_element();
    let media = root
        .children()
        .find(|n| {
            n.is_element()
                && n.tag_name().name() == "Override"
                && n.attribute("PartName") == Some(d.part_name.as_str())
        })
        .or_else(|| {
            root.children().find(|n| {
                n.is_element()
                    && n.tag_name().name() == "Default"
                    && n.attribute("Extension")
                        .is_some_and(|e| e.eq_ignore_ascii_case("xml"))
            })
        })
        .ok_or_else(|| reject("missing effective media declaration"))?;
    let rel_bytes = &relationships[rel.range()];
    let media_bytes = &content_types[media.range()];
    if rel_bytes.len() + media_bytes.len() > MAX_POLICY_BYTES {
        return Err(reject("policy metadata row budget"));
    }
    Ok((rel_bytes.to_vec(), media_bytes.to_vec()))
}
